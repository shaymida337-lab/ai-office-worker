def sheet(wb, title, header, rows, widths, first=False):
    ws = wb.active if first else wb.create_sheet(title)
    ws.title = title; ws.sheet_view.rightToLeft = True
    ws.append(header)
    for r in rows: ws.append(r)
    for c in ws[1]:
        c.font = Font(bold=True, color="FFFFFF"); c.fill = PatternFill("solid", fgColor=GREEN)
        c.alignment = Alignment(wrap_text=True, vertical="top")
    for k, w in enumerate(widths, 1): ws.column_dimensions[get_column_letter(k)].width = w
    for row in ws.iter_rows(min_row=2):
        for c in row: c.alignment = Alignment(wrap_text=True, vertical="top")
    ws.freeze_panes = "B2"
    return ws

